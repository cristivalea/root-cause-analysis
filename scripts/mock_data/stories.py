"""The problem stories: hand-written, complete scenarios for the demo and the evaluation.

Each story is one real failure pattern with everything the investigation can find about it:
the incident to analyse, the older incidents of the same problem, the changes (the cause and
the innocent ones), the log lines, the past RCAs and the answer key.

The answer key (the `answer` block) is never shown to the agents. Log citations in it are
written as "@ref" and resolved by the generator to the id of the first line of that burst.

Two groups of stories:
- success: the application should find the cause with good confidence;
- edge: the application should behave correctly when the data is incomplete or misleading
  (no history, a red herring change, a misleading past RCA, a log gap, a cause outside the
  sources).
"""


def inc(incident_id, title, description, severity, detected, resolved, symptoms, mitigation, reported_by,
        rca_required, rca_reason, regions=None, impact=None, ci=None, flow=None):
    return {
        "incident_id": incident_id, "title": title, "description": description, "severity": severity,
        "detected_at": detected, "resolved_at": resolved, "symptoms": symptoms, "initial_mitigation": mitigation,
        "reported_by": reported_by, "rca_required": rca_required, "rca_reason": rca_reason,
        "affected_regions": regions, "impact": impact, "ci_id": ci, "flow": flow,
    }


def chg(change_id, title, description, type_, service, ci, at, by, risk, version=None, rollback=False, role="innocent"):
    return {
        "change_id": change_id, "title": title, "description": description, "type": type_, "service": service,
        "ci_id": ci, "version": version, "implemented_at": at, "implemented_by": by, "risk": risk,
        "rollback": rollback, "role": role,
    }


def burst(ref, start, end, n, level, error_type, messages, hosts, label=None, service=None, ids=None, counter=None):
    """n log lines between start and end. `ids` fixes the ids of existing lines. `counter` (first, last) is the
    value of {n} on the first and the last line, for numbers that grow or fall (a queue depth, days left)."""
    return {
        "ref": ref, "start": start, "end": end, "n": n, "level": level, "error_type": error_type,
        "messages": messages, "hosts": hosts, "label": label, "service": service, "ids": ids, "counter": counter,
    }


